import assert from 'node:assert/strict'
import { test } from 'node:test'
import { LikeC4 } from 'likec4'
import { renderOverlay } from './lib/render.js'

const source = `specification {
  element system
  element container
  element component
  deploymentNode environment
  deploymentNode cluster
  deploymentNode namespace
}

model {
  shop = system {
    api = container
    database = container
    manual = container
    worker = container
    detail = component
  }
}

deployment {
  environment production {
    cluster eu {
      namespace payments {
        manual = instanceOf shop.manual
      }
      namespace my_ns
    }
  }
}
`

const loadedModel = async () => {
  const likec4 = await LikeC4.fromSource(source, { throwIfInvalid: true, logger: false, printErrors: false })
  return likec4.computedModel()
}

const target = {
  deploymentFqn: 'production.eu',
  context: "prod\\east's",
  includedNamespaces: '*',
  excludedNamespaces: [],
  elementAnnotation: 'example.com/element',
  authoredNamespaces: { payments: 'production.eu.payments' },
}

test('renders authored and generated namespaces as a deterministic overlay', async () => {
  const model = await loadedModel()
  const snapshots = [{
    context: target.context,
    deploymentFqn: target.deploymentFqn,
    namespaces: ['workers', 'payments'],
    unmapped: [],
    workloads: [
      {
        namespace: 'workers',
        kind: 'CronJob',
        name: 'nightly-cleanup',
        element: 'shop.worker',
        version: null,
        chart: null,
        desiredImages: ['registry/worker:2'],
        observedImageIds: [],
        replicas: {},
      },
      {
        namespace: 'payments',
        kind: 'Deployment',
        name: 'api-service',
        element: 'shop.api',
        version: '1.8.0',
        chart: 'shop-2.4.0',
        desiredImages: ['registry/sidecar:2', 'registry/api:1.8.0'],
        observedImageIds: ['registry/api@sha256:bbb', 'registry/api@sha256:aaa'],
        replicas: { updated: 1, available: 2, desired: 3, ready: 2 },
      },
    ],
  }]

  const rendered = renderOverlay({ model, targets: [target], snapshots })

  assert.equal(rendered, `// Generated by @architecture-model/kubernetes. Do not edit.

deployment {
  extend production.eu.payments {
    api_service = instanceOf shop.api {
      title 'api-service (Deployment)'
      metadata {
        kubernetesContext 'prod\\\\east\\'s'
        kubernetesNamespace 'payments'
        kubernetesKind 'Deployment'
        kubernetesName 'api-service'
        version '1.8.0'
        helmChart 'shop-2.4.0'
        desiredImages [
          'registry/api:1.8.0',
          'registry/sidecar:2'
        ]
        observedImageIds [
          'registry/api@sha256:aaa',
          'registry/api@sha256:bbb'
        ]
        desiredReplicas '3'
        readyReplicas '2'
        availableReplicas '2'
        updatedReplicas '1'
      }
    }
  }

  extend production.eu {
    namespace workers {
      title 'workers'
      metadata {
        kubernetesNamespace 'workers'
      }
      nightly_cleanup = instanceOf shop.worker {
        title 'nightly-cleanup (CronJob)'
        metadata {
          kubernetesContext 'prod\\\\east\\'s'
          kubernetesNamespace 'workers'
          kubernetesKind 'CronJob'
          kubernetesName 'nightly-cleanup'
          desiredImages [
            'registry/worker:2'
          ]
        }
      }
    }
  }
}
`)
})

test('adds stable hashes when sanitized workload names collide', async () => {
  const model = await loadedModel()
  const workloads = ['my-app', 'my_app'].map((name, index) => ({
    namespace: 'workers',
    kind: index === 0 ? 'Deployment' : 'StatefulSet',
    name,
    element: index === 0 ? 'shop.api' : 'shop.database',
    version: null,
    chart: null,
    desiredImages: [],
    observedImageIds: [],
    replicas: {},
  }))
  const snapshot = {
    context: target.context,
    deploymentFqn: target.deploymentFqn,
    namespaces: ['workers'],
    workloads,
    unmapped: [],
  }

  const rendered = renderOverlay({ model, targets: [target], snapshots: [snapshot] })
  assert.match(rendered, /my_app_794407f4 = instanceOf shop\.api/)
  assert.match(rendered, /my_app_a9f3e7fe = instanceOf shop\.database/)
  assert.match(rendered, /kubernetesName 'my-app'/)
  assert.match(rendered, /kubernetesName 'my_app'/)
})

test('orders workloads by code point independently of locale', async () => {
  const model = await loadedModel()
  const workloads = ['a', 'B'].map(name => ({
    namespace: 'workers',
    kind: 'Deployment',
    name,
    element: 'shop.api',
    version: null,
    chart: null,
    desiredImages: [],
    observedImageIds: [],
    replicas: {},
  }))
  const snapshot = {
    context: target.context,
    deploymentFqn: target.deploymentFqn,
    namespaces: ['workers'],
    workloads,
    unmapped: [],
  }

  const rendered = renderOverlay({ model, targets: [target], snapshots: [snapshot] })

  assert.equal(rendered.indexOf("kubernetesName 'B'") < rendered.indexOf("kubernetesName 'a'"), true)
})

test('does not render selected namespaces without mapped workloads', async () => {
  const model = await loadedModel()
  const snapshot = {
    context: target.context,
    deploymentFqn: target.deploymentFqn,
    namespaces: ['empty', 'workers'],
    workloads: [{
      namespace: 'workers',
      kind: 'CronJob',
      name: 'cleanup',
      element: 'shop.worker',
      version: null,
      chart: null,
      desiredImages: [],
      observedImageIds: [],
      replicas: {},
    }],
    unmapped: [],
  }

  const rendered = renderOverlay({ model, targets: [target], snapshots: [snapshot] })

  assert.doesNotMatch(rendered, /namespace empty/)
  assert.match(rendered, /namespace workers/)
})

test('rejects a generated workload that collides with an authored instance', async () => {
  const model = await loadedModel()
  const snapshot = {
    context: target.context,
    deploymentFqn: target.deploymentFqn,
    namespaces: ['payments'],
    unmapped: [],
    workloads: [{
      namespace: 'payments',
      kind: 'Deployment',
      name: 'manual',
      element: 'shop.api',
      version: null,
      chart: null,
      desiredImages: [],
      observedImageIds: [],
      replicas: {},
    }],
  }

  assert.throws(
    () => renderOverlay({ model, targets: [target], snapshots: [snapshot] }),
    /manual.*authored|authored.*manual/,
  )
})

